// SAFETY: Only IHK's versioned OS object invokes this registered callback. It
// holds an OsLease for the exact slot/generation, its sleepable operation lock,
// and the owning SMP module reference. User pointers live only for this call.
unsafe extern "C" fn ihk_smp_os_ioctl_v2(
    slot: u32,
    generation: u64,
    command: u32,
    argument: u64,
    compat: u32,
) -> i64 {
    if compat > 1 || (compat == 1 && argument > u32::MAX as u64) {
        return EINVAL.to_errno() as i64;
    }
    // SAFETY: IHK supplies the live lease proof described by this callback ABI;
    // these identifiers are not derived from the user's ioctl arguments.
    let owner = match unsafe { smp_resource::OsToken::from_ihk_lease_v2(slot, generation) } {
        Ok(owner) => owner,
        Err(_) => return EINVAL.to_errno() as i64,
    };
    let result = if command == 0x0011_2a00 {
        smp_loader::load(owner, argument as usize)
    } else if command == abi::IHK_OS_SET_KARGS {
        smp_memory::set_kernel_arguments(owner, argument as usize)
    } else if smp_cpu::handles_os(command) {
        smp_cpu::os_ioctl(owner, command, argument as usize, compat == 1)
    } else if smp_memory::handles_os(command) {
        smp_memory::os_ioctl(owner, command, argument as usize, compat == 1)
    } else {
        Err(EINVAL)
    };
    match result {
        Ok(value) => value as i64,
        Err(error) => error.to_errno() as i64,
    }
}

// SAFETY: IHK invokes this only with the exclusive initial-state DestroyGuard
// and the retained SMP module owner. No OS file, boot, or other resource call
// can overlap cleanup for this generation. Errors leave its resources intact.
unsafe extern "C" fn ihk_smp_os_release_v2(slot: u32, generation: u64) -> i32 {
    // SAFETY: The versioned IHK exclusive destruction callback proves the
    // exact generation remains owned until both resource maps are cleaned up.
    let owner = match unsafe { smp_resource::OsToken::from_ihk_lease_v2(slot, generation) } {
        Ok(owner) => owner,
        Err(_) => return EINVAL.to_errno(),
    };
    match smp_cpu::release_os_resources(owner) {
        Ok(()) => 0,
        Err(error) => error.to_errno(),
    }
}

// SAFETY: IHK holds its exact OS lease, per-OS operation mutex and SMP module
// owner. kmsg scalars identify IHK's allocation, never an ioctl user pointer.
unsafe extern "C" fn ihk_smp_prepare_boot_v3(
    slot: u32,
    generation: u64,
    kmsg: u64,
    kmsg_bytes: u64,
) -> i32 {
    // SAFETY: The v3 callback retains the same trusted IHK generation proof.
    let owner = match unsafe { smp_resource::OsToken::from_ihk_lease_v2(slot, generation) } {
        Ok(owner) => owner,
        Err(_) => return EINVAL.to_errno(),
    };
    // SAFETY: The diagnostic parameter is read-only after module init.
    let prepare_only = unsafe { NATIVE_BOOT_PREPARE_ONLY };
    if prepare_only > 1 {
        return EINVAL.to_errno();
    }
    // SAFETY: Reuse the existing writable ihk_trampoline parameter. Linux's
    // parameter mutex excludes concurrent sysfs writes during this scalar
    // snapshot; no parameter lock crosses resource locking or CPU startup.
    let trampoline = unsafe {
        kernel::bindings::kernel_param_lock(THIS_MODULE.as_ptr());
        let value = core::ptr::read_volatile(&raw const IHK_TRAMPOLINE);
        kernel::bindings::kernel_param_unlock(THIS_MODULE.as_ptr());
        value
    };
    match smp_cpu::prepare_os_boot(owner, kmsg, kmsg_bytes, trampoline) {
        Ok(()) if prepare_only == 1 => {
            pr_info!("IHK-SMP: boot preparation held os={} generation={}; diagnostic mode, CPUs not started\n", slot, generation);
            -11
        }
        Ok(()) => 0,
        Err(error) => error.to_errno(),
    }
}

// SAFETY: IHK has already published Booting and excludes resource mutation.
// The native adapter retains every owner before the first CPU-start effect.
unsafe extern "C" fn ihk_smp_start_boot_v3(slot: u32, generation: u64) -> i32 {
    // SAFETY: The v3 start callback carries the same exact-generation lease.
    let owner = match unsafe { smp_resource::OsToken::from_ihk_lease_v2(slot, generation) } {
        Ok(owner) => owner,
        Err(_) => return EINVAL.to_errno(),
    };
    match smp_cpu::start_os_boot(owner) {
        Ok(()) => 0,
        Err(error) => error.to_errno(),
    }
}

// These callbacks deliberately own lifecycle only.  Returning success from
// init does not advertise any device operation, OS lease, CPU, memory, IKC, or
// McKernel behavior.  The IHK provider invokes them before publication and
// while holding an unpublishing guard respectively.
// SAFETY: The callback owns no foreign state and returns only a literal errno
// status through the exact v2 function-pointer ABI.
extern "C" fn ihk_smp_provider_init_v2() -> i32 {
    pr_info!("provider_callback=init status=complete callback_abi=1\n");
    0
}

// SAFETY: The callback owns no foreign state and returns only after its local
// lifecycle diagnostic completes through the exact v2 function-pointer ABI.
extern "C" fn ihk_smp_provider_exit_v2() {
    pr_info!("provider_callback=exit status=complete callback_abi=1\n");
}

fn provider_status_error(status: i64) -> Error {
    let errno = match status {
        -2 | -12 | -16 | -19 | -22 | -75 | -116 | -117 => status as i32,
        _ => -117,
    };
    match kernel::error::to_result(errno) {
        Err(error) => error,
        Ok(()) => EIO,
    }
}

#[must_use = "the provider lease must remain owned until SMP module teardown"]
struct ProviderLease {
    token: i64,
}

impl ProviderLease {
    fn attach() -> Result<Self> {
        // SAFETY: ihk.ko owns the exact namespaced C-ABI function for the
        // dependency lifetime.  The exact callbacks accept no arguments, own
        // no caller memory, and remain resident until the matching detach.
        let token = unsafe {
            ihk_smp_provider_attach_v2(
                IHK_SMP_PROVIDER_CALLBACK_ABI_V1,
                IHK_SMP_PROVIDER_FLAG_SHARED,
                Some(ihk_smp_provider_init_v2),
                Some(ihk_smp_provider_exit_v2),
            )
        };
        if token <= 0 {
            return Err(provider_status_error(token));
        }
        Ok(Self { token })
    }
}

impl Drop for ProviderLease {
    fn drop(&mut self) {
        // SAFETY: This non-Copy owner calls the matching provider function
        // exactly once with the positive token returned by attach and the
        // retained exit identity.  The provider fails stop rather than
        // returning with a live entry or callback.
        unsafe { ihk_smp_provider_detach_v2(self.token, Some(ihk_smp_provider_exit_v2)) };
    }
}

#[must_use = "the provider-open receipt must remain owned until file release"]
struct ProviderOpenLease {
    receipt: i64,
}

impl ProviderOpenLease {
    fn acquire() -> Result<Self> {
        // SAFETY: ihk.ko owns this exact namespaced scalar function for the
        // dependency lifetime.  Minor zero is the only published provider
        // slot in this bounded shell, and no pointer or Rust layout crosses
        // the boundary.
        let receipt = unsafe { ihk_smp_provider_open_v1(IHK_SMP_CONTROL_DEVICE_MINOR) };
        if receipt <= 0 {
            return Err(provider_status_error(receipt));
        }
        Ok(Self { receipt })
    }
}

impl Drop for ProviderOpenLease {
    fn drop(&mut self) {
        // SAFETY: This non-Copy per-file owner calls the matching scalar close
        // exactly once with the positive opaque receipt returned by open.  The
        // shared scalar is not a unique per-file identity, so this trusted
        // non-Copy wrapper is the count-balance authority.  ihk.ko fails stop
        // on a nonpositive, stale, or zero-reference release.
        unsafe { ihk_smp_provider_close_v1(self.receipt) };
    }
}

struct IhkSmpControlDevice;

#[vtable]
impl MiscDevice for IhkSmpControlDevice {
    type Ptr = Box<ProviderOpenLease>;

    const MODULE: &'static ThisModule = &THIS_MODULE;

    fn open() -> Result<Self::Ptr> {
        // Linux 6.12's `BoxExt::new` takes ownership before allocation.  If
        // allocation fails, the temporary ProviderOpenLease is dropped and
        // closes the already-acquired scalar receipt before ENOMEM is returned.
        Box::new(ProviderOpenLease::acquire()?, GFP_KERNEL).map_err(|_| ENOMEM)
    }

    fn ioctl(_device: &ProviderOpenLease, cmd: u32, arg: usize) -> Result<isize> {
        if smp_cpu::handles(cmd) {
            return smp_cpu::ioctl(cmd, arg, false);
        }
        if smp_memory::handles(cmd) {
            return smp_memory::ioctl(cmd, arg, false);
        }
        control_device_request(cmd, arg)
    }

    #[cfg(CONFIG_COMPAT)]
    fn compat_ioctl(_device: &ProviderOpenLease, cmd: u32, arg: usize) -> Result<isize> {
        if smp_cpu::handles(cmd) {
            return smp_cpu::ioctl(cmd, arg as u32 as usize, true);
        }
        if smp_memory::handles(cmd) {
            return smp_memory::ioctl(cmd, arg as u32 as usize, true);
        }
        // This command takes a userspace pointer.  On x86_64 compat callers
        // supply a 32-bit address; zero extension matches compat_ptr().
        control_device_request(cmd, arg as u32 as usize)
    }
}

// This is the x86_64 layout of Linux 6.12's `struct kernel_param`.  Keeping a
// local representation avoids depending on bindgen's unstable anonymous-union
// field name while the size/alignment checks below bind it to the generated
// Rocky kernel type.
#[repr(C)]
union KernelParameterValue {
    arg: *mut core::ffi::c_void,
}

#[repr(C)]
struct KernelParameter {
    name: *const core::ffi::c_char,
    module: *mut kernel::bindings::module,
    ops: *const kernel::bindings::kernel_param_ops,
    permission: u16,
    level: i8,
    flags: u8,
    value: KernelParameterValue,
}

// SAFETY: Each instance is immutable after relocation.  Linux owns access to
// the pointed-to parameter storage and serializes writes with its parameter
// subsystem; the used trampoline value is read under that same mutex.
unsafe impl Sync for KernelParameter {}

const _: [(); core::mem::size_of::<kernel::bindings::kernel_param>()] =
    [(); core::mem::size_of::<KernelParameter>()];
const _: [(); core::mem::align_of::<kernel::bindings::kernel_param>()] =
    [(); core::mem::align_of::<KernelParameter>()];

macro_rules! numeric_parameter {
    (
        name: $name:ident,
        storage: $storage:ident,
        descriptor: $descriptor:ident,
        rust_type: $rust_type:ty,
        ops: $ops:ident,
        default: $default:literal,
        permission: $permission:literal,
        loadable_name_bytes: $loadable_name_bytes:literal,
        builtin_name_bytes: $builtin_name_bytes:literal,
    ) => {
        #[doc(hidden)]
        // SAFETY: Linux's parameter subsystem is the only writer after module
        // publication and serializes access; Rust never reads this storage.
        static mut $storage: $rust_type = $default;

        #[doc(hidden)]
        #[link_section = "__param"]
        #[used(compiler)]
        static $descriptor: KernelParameter = KernelParameter {
            name: {
                #[cfg(MODULE)]
                const PARAMETER_NAME: &[u8] = $loadable_name_bytes;
                #[cfg(not(MODULE))]
                const PARAMETER_NAME: &[u8] = $builtin_name_bytes;
                PARAMETER_NAME.as_ptr() as *const core::ffi::c_char
            },
            module: THIS_MODULE.as_ptr(),
            // `param_ops_uint` and `param_ops_ulong` are immutable, exported
            // Linux kernel objects with static lifetime.
            ops: core::ptr::addr_of!(kernel::bindings::$ops),
            permission: $permission,
            level: -1,
            flags: 0,
            value: KernelParameterValue {
                arg: core::ptr::addr_of_mut!($storage) as *mut core::ffi::c_void,
            },
        };

        // Make the contract name part of the expansion even though the ABI
        // consumes its explicitly NUL-terminated byte form above.
        const _: &str = stringify!($name);
    };
}

