const IHK_SMP_PARAMETER_COUNT: usize = 6;
const IHK_SMP_DEPENDENCY: &str = "ihk";
const IHK_SMP_IMPORT_NAMESPACE: &str = "MCKERNEL_IHK_V1";
const IHK_SMP_PROVIDER_CALLBACK_ABI_V1: u32 = 1;
const IHK_SMP_PROVIDER_FLAG_SHARED: u32 = 1;
const IHK_SMP_CONTROL_DEVICE_MINOR: u32 = 0;

const IHK_DEVICE_GET_BUILDID: u32 = 0x0011_290b;
const IHK_DEVICE_CREATE_OS: u32 = 0x0011_2900;
const IHK_DEVICE_DESTROY_OS: u32 = 0x0011_2901;
// Generated by the authoritative stager from the unchanged IHK consumers'
// BUILDID rule.  Those consumers allocate sizeof(BUILDID), so this payload
// must retain their exact bytes and trailing NUL.  Native source provenance
// is recorded separately in stage-lock.json, not substituted into this UAPI.
const IHK_COMPAT_BUILD_ID: &[u8] = include_bytes!("ihk-compat-build-id.bin");

fn control_device_ioctl(cmd: u32, arg: usize) -> Result<isize> {
    match cmd {
        IHK_DEVICE_GET_BUILDID => {
            kernel::uaccess::UserSlice::new(arg, IHK_COMPAT_BUILD_ID.len())
                .writer()
                .write_slice(IHK_COMPAT_BUILD_ID)?;
            Ok(0)
        }
        _ => Err(EINVAL),
    }
}

fn control_device_request(cmd: u32, arg: usize) -> Result<isize> {
    match cmd {
        IHK_DEVICE_CREATE_OS => {
            // SAFETY: This callback runs with the SMP control file pinning
            // THIS_MODULE. IHK acquires its own module reference before the
            // instance becomes live; the raw scalar argument is never a pointer.
            let result = unsafe {
                ihk_os_create_unbooted_v3(
                    IHK_SMP_CONTROL_DEVICE_MINOR,
                    THIS_MODULE.as_ptr().cast(),
                    arg as u64,
                    1,
                    Some(ihk_smp_os_ioctl_v2),
                    Some(ihk_smp_os_release_v2),
                    Some(ihk_smp_prepare_boot_v3),
                    Some(ihk_smp_start_boot_v3),
                )
            };
            if result < 0 {
                Err(provider_status_error(result))
            } else {
                Ok(result as isize)
            }
        }
        IHK_DEVICE_DESTROY_OS => {
            // SAFETY: IHK owns this scalar ABI for the dependency lifetime.
            // It validates the provider and minor and refuses open instances.
            let result =
                unsafe { ihk_os_destroy_unbooted_v1(IHK_SMP_CONTROL_DEVICE_MINOR, arg as u64) };
            if result < 0 {
                Err(provider_status_error(result))
            } else {
                Ok(result as isize)
            }
        }
        _ => control_device_ioctl(cmd, arg),
    }
}

